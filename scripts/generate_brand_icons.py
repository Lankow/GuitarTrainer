"""Regenerate Android icons from src/brandGeometry.ts (Pillow and Shapely required)."""
from pathlib import Path
import re
from PIL import Image, ImageDraw
from shapely.geometry import Point, Polygon
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'native/android/app/src/main/res'
SOURCE = (ROOT / 'src/brandGeometry.ts').read_text()
ORANGE = '#f5a45d'
CHARCOAL = '#151916'


def geometry(name):
    """Flatten the master's absolute M/H/V/C/Q/Z paths for Android and raster export."""
    path = re.search(rf"export const {name} = '([^']+)'", SOURCE).group(1)
    tokens = re.findall(r'[A-Za-z]|-?\d+(?:\.\d+)?', path)
    shapes, points = [], []
    x = y = 0.0
    i = 0
    while i < len(tokens):
        command = tokens[i]
        i += 1
        if command == 'Z':
            shapes.append(Polygon(points))
            points = []
            continue
        count = {'M': 2, 'H': 1, 'V': 1, 'C': 6, 'Q': 4}[command]
        values = list(map(float, tokens[i:i + count]))
        i += count
        if command == 'M':
            x, y = values
        elif command == 'H':
            x = values[0]
        elif command == 'V':
            y = values[0]
        else:
            start_x, start_y = x, y
            for step in range(1, 65):
                t = step / 64
                u = 1 - t
                if command == 'C':
                    a, b, c, d, e, f = values
                    x = u**3 * start_x + 3*u*u*t*a + 3*u*t*t*c + t**3*e
                    y = u**3 * start_y + 3*u*u*t*b + 3*u*t*t*d + t**3*f
                else:
                    a, b, c, d = values
                    x = u*u*start_x + 2*u*t*a + t*t*c
                    y = u*u*start_y + 2*u*t*b + t*t*d
                points.append((x, y))
        points.append((x, y))
    return unary_union(shapes)


outline = geometry('brandOutline')
cx, cy, radius = map(float, re.search(r'brandHole = \[([^]]+)\]', SOURCE).group(1).split(','))
hole = Point(cx, cy).buffer(radius, quad_segs=64)
cutouts = geometry('brandCutouts').union(hole)
mark = outline.difference(cutouts).union(outline.intersection(geometry('brandRails')))
assert mark.is_valid and not mark.is_empty
polygons = list(mark.geoms) if hasattr(mark, 'geoms') else [mark]
left, top, right, bottom = mark.bounds
center_x, center_y = (left + right) / 2, (top + bottom) / 2


def mapped_ring(ring, size, height):
    scale = height / (bottom - top)
    return [((x-center_x)*scale+size/2, (y-center_y)*scale+size/2) for x, y in ring.coords]


def vector_path():
    parts = []
    for polygon in polygons:
        for ring in [polygon.exterior, *polygon.interiors]:
            coords = mapped_ring(ring, 108, 60)
            parts.append('M' + 'L'.join(f'{x:.3f},{y:.3f}' for x, y in coords) + 'Z')
    return ''.join(parts)


vector = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_brand_icons.py; edit src/brandGeometry.ts. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{ORANGE}" android:fillType="evenOdd"
        android:pathData="{vector_path()}" />
</vector>
'''
(RES / 'drawable-v24/ic_launcher_foreground.xml').write_text(vector)
for name in ['ic_launcher', 'ic_launcher_round']:
    (RES / f'mipmap-anydpi-v26/{name}.xml').write_text('''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground" />
</adaptive-icon>
''')
(RES / 'values/ic_launcher_background.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<resources><color name="ic_launcher_background">{CHARCOAL}</color></resources>
''')


def raster(size, mode):
    # Supersample before reducing to preserve thin string/fret details.
    full = size * 4
    image = Image.new('RGBA', (full, full))
    draw = ImageDraw.Draw(image)
    if mode == 'round':
        draw.ellipse((0, 0, full-1, full-1), fill=CHARCOAL)
    elif mode == 'legacy':
        draw.rounded_rectangle((0, 0, full-1, full-1), radius=full*.18, fill=CHARCOAL)
    mask = Image.new('L', (full, full))
    pen = ImageDraw.Draw(mask)
    height = full * (60 / 108 if mode == 'foreground' else .72)
    for polygon in polygons:
        pen.polygon(mapped_ring(polygon.exterior, full, height), fill=255)
        for ring in polygon.interiors:
            pen.polygon(mapped_ring(ring, full, height), fill=0)
    image.paste(Image.new('RGBA', (full, full), ORANGE), mask=mask)
    return image.resize((size, size), Image.Resampling.LANCZOS)


for density, size in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
    folder = RES / f'mipmap-{density}'
    raster(size, 'legacy').save(folder / 'ic_launcher.png')
    raster(size, 'round').save(folder / 'ic_launcher_round.png')
    raster(round(size * 108 / 48), 'foreground').save(folder / 'ic_launcher_foreground.png')
print('Generated adaptive vector, monochrome layer and five legacy/foreground densities.')

# A local review sheet is build output, not part of the source assets.
preview = ROOT / 'build/branding-preview.png'
preview.parent.mkdir(exist_ok=True)
sheet = Image.new('RGBA', (768, 256), '#eeeeee')
for i, mode in enumerate(['legacy', 'round', 'foreground']):
    sheet.alpha_composite(raster(224, mode), (i * 256 + 16, 16))
sheet.convert('RGB').save(preview)
